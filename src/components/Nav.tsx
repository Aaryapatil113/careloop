"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";
import { useEffect, useState } from "react";

const LINKS = [
  { href: "/", label: "Overview" },
  { href: "/patient", label: "Patient app" },
  { href: "/clinician", label: "Clinician portal" },
  { href: "/observability", label: "Traces" },
  { href: "/evals", label: "Evals" },
];

export function Nav() {
  const path = usePathname();
  const [mode, setMode] = useState<string>();
  useEffect(() => {
    fetch("/api/patients")
      .then((r) => r.json())
      .then((d) => setMode(d.mode))
      .catch(() => {});
  }, []);
  return (
    <header className="sticky top-0 z-10 border-b border-slate-200 bg-white/90 backdrop-blur">
      <div className="mx-auto flex max-w-6xl flex-wrap items-center gap-x-6 gap-y-2 px-4 py-3 sm:px-6">
        <Link href="/" className="flex items-center gap-2 font-semibold text-slate-900">
          <span className="grid h-7 w-7 place-items-center rounded-lg bg-teal-700 text-sm text-white">C</span>
          CareLoop
        </Link>
        <nav className="flex flex-wrap gap-1 text-sm">
          {LINKS.map((l) => (
            <Link
              key={l.href}
              href={l.href}
              className={`rounded-md px-2.5 py-1.5 ${path === l.href ? "bg-teal-50 font-medium text-teal-800" : "text-slate-600 hover:bg-slate-100"}`}
            >
              {l.label}
            </Link>
          ))}
        </nav>
        {mode && (
          <span
            title={mode === "live" ? "Responses generated by Claude" : "No API key set: deterministic retrieval-grounded responder"}
            className={`ml-auto rounded-full px-2.5 py-1 text-xs font-medium ${mode === "live" ? "bg-emerald-100 text-emerald-800" : "bg-amber-100 text-amber-800"}`}
          >
            {mode === "live" ? "● Live · Claude" : "● Demo mode"}
          </span>
        )}
      </div>
    </header>
  );
}
